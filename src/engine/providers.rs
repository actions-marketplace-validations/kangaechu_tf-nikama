//! Provider allowlist: source-address patterns and the Terraform CLI
//! configuration that enforces them.
//!
//! Patterns are provider source addresses (`hostname/namespace/type`) where
//! any segment may be `*`. `namespace/type` is short for
//! `registry.terraform.io/namespace/type`, as in Terraform itself.

const DEFAULT_HOST: &str = "registry.terraform.io";

/// Split a comma- or whitespace-separated list and normalise every entry.
pub fn parse_list(s: &str) -> Result<Vec<String>, String> {
    let mut out = Vec::new();
    for raw in s.split(|c: char| c == ',' || c.is_whitespace()) {
        let raw = raw.trim();
        if raw.is_empty() {
            continue;
        }
        let p = normalize(raw)?;
        if !out.contains(&p) {
            out.push(p);
        }
    }
    Ok(out)
}

/// Normalise one pattern: lower-case, default hostname, 3 non-empty segments.
pub fn normalize(p: &str) -> Result<String, String> {
    let p = p.trim().to_ascii_lowercase();
    let segs: Vec<&str> = p.split('/').collect();
    let segs: Vec<&str> = match segs.len() {
        2 => vec![DEFAULT_HOST, segs[0], segs[1]],
        3 => segs,
        _ => {
            return Err(format!(
                "invalid provider pattern '{}': expected namespace/type or hostname/namespace/type",
                p
            ))
        }
    };
    for s in &segs {
        if s.is_empty() {
            return Err(format!("invalid provider pattern '{}': empty segment", p));
        }
        if s.contains('*') && *s != "*" {
            return Err(format!(
                "invalid provider pattern '{}': '*' must replace a whole segment",
                p
            ));
        }
    }
    Ok(segs.join("/"))
}

/// Does every provider matched by `inner` also match `outer`? Both must be
/// normalised.
pub fn covers(outer: &str, inner: &str) -> bool {
    outer
        .split('/')
        .zip(inner.split('/'))
        .all(|(o, i)| o == "*" || o == i)
}

/// The allowlist a run is executed with.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Allowlist {
    pub patterns: Vec<String>,
    /// Where the effective list came from, for logging.
    pub source: &'static str,
}

/// Combine the workflow input (trusted) with the `allowed_providers` list of
/// `nikama.yml` (may only narrow). `None` when neither is set.
pub fn effective(input: Option<&[String]>, config: &[String]) -> Result<Option<Allowlist>, String> {
    match (input, config.is_empty()) {
        (None, true) => Ok(None),
        (Some(i), true) => Ok(Some(Allowlist {
            patterns: i.to_vec(),
            source: "allowed-providers",
        })),
        (None, false) => Ok(Some(Allowlist {
            patterns: config.to_vec(),
            source: "nikama.yml allowed_providers (no allowed-providers input; the list is controlled by the configuration)",
        })),
        (Some(i), false) => {
            let (kept, dropped): (Vec<&String>, Vec<&String>) =
                config.iter().partition(|c| i.iter().any(|o| covers(o, c)));
            if !dropped.is_empty() {
                tracing::warn!(
                    dropped = %dropped.iter().map(|s| s.as_str()).collect::<Vec<_>>().join(", "),
                    "allowed_providers entries in nikama.yml outside the allowed-providers input are ignored"
                );
            }
            if kept.is_empty() {
                return Err(format!(
                    "allowed_providers in nikama.yml ({}) has no entry within the allowed-providers input ({})",
                    config.join(", "),
                    i.join(", ")
                ));
            }
            Ok(Some(Allowlist {
                patterns: kept.into_iter().cloned().collect(),
                source: "allowed-providers narrowed by nikama.yml allowed_providers",
            }))
        }
    }
}

/// Terraform / OpenTofu CLI configuration enforcing `patterns`, appended to
/// the user's existing configuration when there is one.
pub fn cli_config(patterns: &[String], existing: Option<&str>) -> Result<String, String> {
    let mut out = String::new();
    if let Some(e) = existing {
        if e.contains("provider_installation") {
            return Err(
                "the existing Terraform CLI configuration already has a provider_installation block; \
                 put the include list there instead of using allowed-providers"
                    .to_string(),
            );
        }
        out.push_str(e.trim_end());
        out.push_str("\n\n");
    }
    let list = patterns
        .iter()
        .map(|p| format!("\"{}\"", p))
        .collect::<Vec<_>>()
        .join(", ");
    out.push_str("# Generated by nikama from allowed-providers; providers outside the list cannot be installed.\n");
    out.push_str("provider_installation {\n  direct {\n    include = [");
    out.push_str(&list);
    out.push_str("]\n  }\n}\n");
    Ok(out)
}

/// The CLI configuration Terraform would read without us: `TF_CLI_CONFIG_FILE`,
/// then `~/.terraformrc`, then `~/.tofurc`.
pub fn existing_cli_config() -> std::io::Result<Option<String>> {
    let mut candidates = Vec::new();
    if let Some(p) = crate::util::env_opt("TF_CLI_CONFIG_FILE") {
        candidates.push(std::path::PathBuf::from(p));
    } else if let Some(home) = crate::util::env_opt("HOME") {
        candidates.push(std::path::Path::new(&home).join(".terraformrc"));
        candidates.push(std::path::Path::new(&home).join(".tofurc"));
    }
    for c in candidates {
        if c.is_file() {
            return std::fs::read_to_string(&c).map(Some);
        }
    }
    Ok(None)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn normalises_patterns() {
        assert_eq!(
            normalize("hashicorp/AWS").unwrap(),
            "registry.terraform.io/hashicorp/aws"
        );
        assert_eq!(
            normalize("hashicorp/*").unwrap(),
            "registry.terraform.io/hashicorp/*"
        );
        assert_eq!(
            normalize("app.terraform.io/org/thing").unwrap(),
            "app.terraform.io/org/thing"
        );
        assert_eq!(normalize("*/*/*").unwrap(), "*/*/*");
        for bad in ["aws", "a/b/c/d", "hashicorp/", "/aws", "hashicorp/aws*"] {
            assert!(normalize(bad).is_err(), "{}", bad);
        }
        assert_eq!(
            parse_list(" hashicorp/aws, hashicorp/aws\nhashicorp/*,").unwrap(),
            vec![
                "registry.terraform.io/hashicorp/aws",
                "registry.terraform.io/hashicorp/*"
            ]
        );
        assert!(parse_list("").unwrap().is_empty());
    }

    #[test]
    fn covers_with_wildcards() {
        let aws = "registry.terraform.io/hashicorp/aws";
        let any_hashicorp = "registry.terraform.io/hashicorp/*";
        assert!(covers(aws, aws));
        assert!(covers(any_hashicorp, aws));
        assert!(covers(any_hashicorp, any_hashicorp));
        assert!(!covers(aws, any_hashicorp));
        assert!(!covers(any_hashicorp, "registry.terraform.io/other/aws"));
        assert!(covers("*/*/*", "example.com/x/y"));
    }

    fn v(items: &[&str]) -> Vec<String> {
        items.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn effective_list_narrows_only() {
        assert_eq!(effective(None, &[]).unwrap(), None);
        let input = v(&["registry.terraform.io/hashicorp/*"]);
        assert_eq!(
            effective(Some(&input), &[]).unwrap().unwrap().patterns,
            input
        );
        let cfg = v(&["registry.terraform.io/hashicorp/aws"]);
        assert_eq!(effective(None, &cfg).unwrap().unwrap().patterns, cfg);
        // Narrowing keeps the covered entries and drops the rest.
        let cfg = v(&[
            "registry.terraform.io/hashicorp/aws",
            "registry.terraform.io/evil/*",
        ]);
        assert_eq!(
            effective(Some(&input), &cfg).unwrap().unwrap().patterns,
            v(&["registry.terraform.io/hashicorp/aws"])
        );
        // The configuration cannot widen the input.
        let cfg = v(&["registry.terraform.io/evil/thing"]);
        let err = effective(Some(&input), &cfg).unwrap_err();
        assert!(err.contains("no entry within"), "{}", err);
    }

    #[test]
    fn renders_cli_config() {
        let text = cli_config(&v(&["registry.terraform.io/hashicorp/*"]), None).unwrap();
        assert!(text.contains("provider_installation {"));
        assert!(text.contains("include = [\"registry.terraform.io/hashicorp/*\"]"));
        let text = cli_config(
            &v(&["a/b/c", "d/e/f"]),
            Some("plugin_cache_dir = \"/cache\"\n"),
        )
        .unwrap();
        assert!(text.starts_with("plugin_cache_dir = \"/cache\"\n\n"));
        assert!(text.contains("include = [\"a/b/c\", \"d/e/f\"]"));
        let err = cli_config(&v(&["a/b/c"]), Some("provider_installation {}")).unwrap_err();
        assert!(
            err.contains("already has a provider_installation"),
            "{}",
            err
        );
    }
}
